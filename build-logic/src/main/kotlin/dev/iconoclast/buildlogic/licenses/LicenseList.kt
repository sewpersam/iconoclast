package dev.iconoclast.buildlogic.licenses

import javax.xml.parsers.DocumentBuilderFactory
import org.w3c.dom.Element

/** One runtime dependency: Maven coordinates and its licences' SPDX ids. */
data class Dependency(val group: String, val name: String, val version: String, val licenses: List<String>) {
    val coordinates: String get() = "$group:$name:$version"
}

/** What a POM says: its licences, raw names, and its parent's coordinates when it has one. */
data class Pom(val licenses: List<String>, val parent: Triple<String, String, String>?)

/**
 * The open source licence list, M7 readiness item 8: every artifact on the app's release
 * runtime classpath with its licence, read from its POM or the nearest parent POM that
 * declares one. The app shows [asset]; THIRD_PARTY_LICENSES.md carries [markdown] between
 * [START] and [END].
 */
object LicenseList {
    const val START = "<!-- dependencies:start, generated by :app:writeDependencyLicenses -->"
    const val END = "<!-- dependencies:end -->"

    fun parsePom(xml: ByteArray): Pom {
        val f = DocumentBuilderFactory.newInstance().apply {
            isNamespaceAware = false
            setFeature("http://apache.org/xml/features/disallow-doctype-decl", true)
        }
        val root = f.newDocumentBuilder().parse(xml.inputStream()).documentElement
        val licenses = root.child("licenses")?.children("license").orEmpty().mapNotNull { it.text("name") ?: it.text("url") }
        val parent = root.child("parent")?.let { p ->
            val g = p.text("groupId"); val a = p.text("artifactId"); val v = p.text("version")
            if (g != null && a != null && v != null) Triple(g, a, v) else null
        }
        return Pom(licenses, parent)
    }

    /** An SPDX id for the licence names POMs use; an unknown name is kept as written. */
    fun spdx(name: String): String {
        val n = name.lowercase()
        return when {
            "apache" in n && "2" in n -> "Apache-2.0"
            n.contains("mit") && !n.contains("submit") -> "MIT"
            "bsd" in n && ("3" in n || "new" in n || "revised" in n) -> "BSD-3-Clause"
            "bsd" in n && "2" in n -> "BSD-2-Clause"
            "eclipse public license" in n && "2" in n -> "EPL-2.0"
            else -> name.trim()
        }
    }

    /**
     * Free licences as [spdx] names them. Each is on the FSF, OSI or DFSG list that
     * https://f-droid.org/docs/Inclusion_Policy/ defers to. Anything else fails the check
     * until a person reads it and adds it here.
     */
    val FREE = setOf(
        "Apache-2.0", "MIT", "BSD-2-Clause", "BSD-3-Clause", "EPL-1.0", "EPL-2.0", "MPL-2.0", "ISC",
        "LGPL-2.1-only", "LGPL-2.1-or-later", "LGPL-3.0-only", "LGPL-3.0-or-later", "CC0-1.0",
    )

    /**
     * Group prefixes F-Droid's scanner rejects whatever the POM says, from the SUSS list
     * https://fdroid.gitlab.io/fdroid-suss/suss.json (read 2026-10-11): Play Services,
     * Firebase, Crashlytics and Fabric, Facebook, Play Core, Play Billing, Install Referrer,
     * Google ads. `fdroid/check_origins.py` runs the whole list against every classpath.
     */
    val NON_FREE_GROUPS = listOf(
        "com.google.android.gms", "com.google.firebase", "com.crashlytics", "io.fabric", "com.facebook",
        "com.google.android.play", "com.android.billingclient", "com.android.installreferrer",
        "com.google.android.ads", "com.google.ads",
    )

    /** Why [deps] cannot ship on F-Droid: a non-free licence or a known non-free artifact. */
    fun problems(deps: List<Dependency>): List<String> = deps.flatMap { d ->
        buildList {
            if (NON_FREE_GROUPS.any { d.group == it || d.group.startsWith("$it.") }) add("${d.coordinates} is a known non-free artifact")
            // An artifact under several licences may be used under any one of them.
            if (d.licenses.none { it in FREE }) add("${d.coordinates} has no free licence: ${d.licenses.joinToString()}")
        }
    }

    /** One line per artifact, `group:name:version<TAB>licences`, sorted. */
    fun asset(deps: List<Dependency>): String =
        deps.sortedBy { it.coordinates }.joinToString("") { "${it.coordinates}\t${it.licenses.joinToString(" OR ")}\n" }

    /** The markdown table between the markers. */
    fun markdown(deps: List<Dependency>): String = buildString {
        append(START).append('\n')
        append("| Artifact | Version | Licence |\n|---|---|---|\n")
        for (d in deps.sortedBy { it.coordinates }) append("| `${d.group}:${d.name}` | ${d.version} | ${d.licenses.joinToString(" OR ")} |\n")
        append(END)
    }

    /** [doc] with its marked section replaced by [section]. Throws when the markers are missing. */
    fun replaceSection(doc: String, section: String): String {
        val s = doc.indexOf(START)
        val e = doc.indexOf(END)
        require(s >= 0 && e > s) { "THIRD_PARTY_LICENSES.md has no generated dependency section markers" }
        return doc.substring(0, s) + section + doc.substring(e + END.length)
    }

    private fun Element.child(tag: String): Element? = children(tag).firstOrNull()

    private fun Element.children(tag: String): List<Element> {
        val out = ArrayList<Element>()
        val nodes = childNodes
        for (i in 0 until nodes.length) (nodes.item(i) as? Element)?.takeIf { it.tagName == tag }?.let(out::add)
        return out
    }

    private fun Element.text(tag: String): String? = child(tag)?.textContent?.trim()?.takeIf { it.isNotEmpty() }
}
